import type { ComponentProps } from '@blocknote/react'
import type { ComponentProps as ReactComponentProps, ReactNode } from 'react'
import * as Menu from '@radix-ui/react-dropdown-menu'
import { Button } from '@/components/ui/ztd-me/client'
import { cn } from '@/components/ui/ztd-me/ui/cn'
import { MenuDropdown, MenuRoot, MenuTrigger } from '@/features/editor/adapters/components-menu'
import { useBlogTranslation } from '@/i18n/use-translation'

const template1Class = [
  'editor-toolbar p-1 border border-border rounded-[12px] bg-card text-foreground',
  'shadow-[0_12px_32px_var(--blog-shadow-overlay)] flex flex-wrap gap-[2px]',
  '[&_button]:border-transparent [&_button]:bg-transparent',
].join(' ')

const template2Class = [
  'editor-block-type-select max-w-38 [&_>_span]:min-w-0 [&_>_span]:overflow-hidden',
  '[&_>_span]:[text-overflow:ellipsis] [&_>_span]:whitespace-nowrap',
].join(' ')

export function ToolbarRoot({
  className,
  children,
  onMouseEnter,
  onMouseLeave,
}: ComponentProps['FormattingToolbar']['Root']): ReactNode {
  const { t } = useBlogTranslation('editor')
  return (
    <div
      className={cn(template1Class, className ?? '')}
      role="toolbar"
      aria-label={t('formatting')}
      onMouseEnter={onMouseEnter}
      onMouseLeave={onMouseLeave}
    >
      {children}
    </div>
  )
}
export type EditorToolbarButtonProps = ComponentProps['FormattingToolbar']['Button']
  & Omit<ReactComponentProps<typeof Button>, 'variant' | 'children' | 'onClick'>
  & { 'data-test'?: string }

export function ToolbarButton({
  className,
  mainTooltip,
  secondaryTooltip,
  icon,
  label,
  isSelected,
  isDisabled,
  children,
  onClick,
  onPointerDown,
  onMouseDown,
  variant,
  ...rest
}: EditorToolbarButtonProps): ReactNode {
  return (
    <Button
      {...rest}
      variant="outline"
      type="button"
      className={className}
      title={[mainTooltip, secondaryTooltip].filter(Boolean).join(' · ')}
      aria-label={label ?? mainTooltip}
      aria-pressed={isSelected}
      data-toolbar-variant={variant}
      disabled={isDisabled}
      onPointerDown={onPointerDown}
      onMouseDown={(event) => {
        // Protect selection without suppressing the click generated by a WebKit touch tap.
        onMouseDown?.(event)
        if (event.button === 0) {
          event.preventDefault()
        }
      }}
      onClick={onClick}
    >
      {icon}
      {children}
    </Button>
  )
}
export function ToolbarSelect({
  items,
  isDisabled,
  className,
  ...settings
}: ComponentProps['FormattingToolbar']['Select']): ReactNode {
  const { t } = useBlogTranslation('editor')
  return (
    <MenuRoot {...settings}>
      <MenuTrigger>
        <Button
          variant="outline"
          type="button"
          className={cn(template2Class, className ?? '')}
          disabled={isDisabled}
          aria-label={t('blockType')}
        >
          <span>{items.find(item => item.isSelected)?.text ?? t('block')}</span>
        </Button>
      </MenuTrigger>
      <MenuDropdown>
        {items.map(item => (
          <Menu.Item key={item.text} disabled={item.isDisabled} onSelect={item.onClick}>
            {item.icon}
            {item.text}
          </Menu.Item>
        ))}
      </MenuDropdown>
    </MenuRoot>
  )
}
