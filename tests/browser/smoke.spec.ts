import { expect, test } from '@playwright/test'

test('desktop shell navigates home search and real Notion article content', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('link', { name: 'Reliable systems & small tools', exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Site navigation' }).getByRole('link', { name: 'Search' }).click()
  await expect(page.getByRole('heading', { name: 'Search published writing' })).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search terms' }).fill('reliable')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('link', { name: /Reliable systems & small tools/ }).click()
  await expect(page.getByRole('heading', { name: 'Reliable systems & small tools', exact: true })).toBeVisible()
  await expect(page.locator('.notion').getByRole('heading', { name: 'Designing for recovery' })).toBeVisible()
  await expect(page.locator('.notion b')).toHaveText(' Strong evidence.')
  await expect(page.locator('.notion table')).toContainText('Failure')
  await expect(page.locator('.notion pre')).toContainText('const recovery = true;')
  await expect(page.locator('.notion .katex').first()).toBeVisible()
  await page.locator('.notion').getByText('Read the recovery detail', { exact: true }).click()
  await expect(page.locator('.notion').getByText('Nested recovery instructions.', { exact: true })).toBeVisible()
  await page.locator('.notion').getByRole('link', { name: 'About this notebook' }).click()
  await expect(page).toHaveURL('/pages/about')
  await expect(page.locator('.notion')).toContainText('This notebook is served from Notion.')
  await page.getByRole('link', { name: 'zeithrold/blog' }).click()
  await expect(page.getByRole('heading', { name: 'Latest writing' })).toBeVisible()
})

test('mobile menu keyboard controls appearance and returns focus on Escape', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const more = page.getByRole('button', { name: 'More options' })
  await expect(more).toBeEnabled()
  await more.focus()
  await page.keyboard.press('Enter')
  const menu = page.getByRole('dialog', { name: 'More options' })
  await expect(menu).toBeVisible()
  const appearance = menu.getByRole('button', { name: 'Appearance', exact: true })
  await expect(appearance).toBeFocused()
  await page.keyboard.press('Enter')
  const dark = page.getByRole('menuitemradio', { name: 'Dark', exact: true })
  await expect(page.getByRole('menuitemradio', { name: 'System', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitemradio', { name: 'Light', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(dark).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('html')).toHaveAttribute('data-frontend-mode', 'dark')
  await expect(appearance).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(more).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(menu.getByRole('link', { name: 'Subscribe via RSS' })).toHaveAttribute('href', '/rss.xml')
  await page.keyboard.press('Escape')
  await expect(more).toBeFocused()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-frontend-mode', 'dark')
  await page.getByRole('navigation', { name: 'Site navigation' }).getByRole('link', { name: 'Search' }).click()
  await expect(page.getByRole('searchbox', { name: 'Search terms' })).toBeVisible()
})

test('missing public articles show recovery navigation at a narrow width', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const response = await page.goto('/posts/unreleased-secret')
  expect(response?.status()).toBe(404)
  await expect(page.getByRole('heading', { name: 'Not found', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Return to the blog' }).click()
  await expect(page).toHaveURL('/')
  await expect(page.getByRole('link', { name: 'A second field note', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Unreleased secret notebook', exact: true })).toHaveCount(0)
})
